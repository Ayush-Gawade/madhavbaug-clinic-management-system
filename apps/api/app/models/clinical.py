"""Clinical data models: patients, categories, consent, observations, care plans."""

from __future__ import annotations

import enum
import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy import (
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    Numeric,
    String,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, TimestampMixin, UUIDPrimaryKeyMixin


class PatientStatus(enum.StrEnum):
    ACTIVE = "active"
    INACTIVE = "inactive"
    ARCHIVED = "archived"


class PatientCategoryType(enum.StrEnum):
    THYROID = "thyroid"
    OBESITY = "obesity"
    BLOOD_PRESSURE = "blood_pressure"
    DIABETES = "diabetes"


class ConsentType(enum.StrEnum):
    COMMUNICATION = "communication"
    HEALTH_DATA = "health_data"


class ConsentStatus(enum.StrEnum):
    ACTIVE = "active"
    WITHDRAWN = "withdrawn"


class CarePlanStatus(enum.StrEnum):
    DRAFT = "draft"
    ACTIVE = "active"
    ARCHIVED = "archived"


class ObservationSource(enum.StrEnum):
    PATIENT_REPORT = "patient_report"
    STAFF_ENTRY = "staff_entry"
    WHATSAPP = "whatsapp"


class ObservationValidationStatus(enum.StrEnum):
    PENDING = "pending"
    VALIDATED = "validated"
    INVALID = "invalid"
    NEEDS_CLARIFICATION = "needs_clarification"


class ObservationReviewStatus(enum.StrEnum):
    PENDING = "pending"
    REVIEWED = "reviewed"


def _enum(enum_cls: type[enum.StrEnum], name: str) -> Enum:
    """Build a native PostgreSQL enum from a StrEnum."""
    return Enum(enum_cls, name=name, values_callable=lambda e: [m.value for m in e])


class Patient(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """A registered clinic patient."""

    __tablename__ = "patients"
    __table_args__ = (Index("ix_patients_phone", "phone_number"),)

    internal_id: Mapped[str] = mapped_column(String(20), unique=True, index=True, nullable=False)
    full_name: Mapped[str] = mapped_column(String(255), nullable=False)
    phone_number: Mapped[str | None] = mapped_column(String(32), nullable=True)
    preferred_language: Mapped[str] = mapped_column(String(16), default="en", nullable=False)
    date_of_onboarding: Mapped[date | None] = mapped_column(Date, nullable=True)
    assigned_clinician_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("staff_users.id", ondelete="SET NULL"),
        nullable=True,
    )
    status: Mapped[PatientStatus] = mapped_column(
        _enum(PatientStatus, "patient_status"), default=PatientStatus.ACTIVE, nullable=False
    )
    dietary_restrictions: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    communication_preferences: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    categories: Mapped[list[PatientCategory]] = relationship(
        back_populates="patient", cascade="all, delete-orphan", lazy="selectin"
    )
    consents: Mapped[list[ConsentRecord]] = relationship(
        back_populates="patient", cascade="all, delete-orphan", lazy="selectin"
    )
    observations: Mapped[list[Observation]] = relationship(
        back_populates="patient", cascade="all, delete-orphan", lazy="selectin"
    )
    care_plans: Mapped[list[CarePlan]] = relationship(
        back_populates="patient", cascade="all, delete-orphan", lazy="selectin"
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Patient {self.internal_id} {self.full_name}>"


class PatientCategory(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """An operational label linking a patient to a health category.

    Categories are operational labels, not diagnoses generated by the software
    (PRD FR-002). Multiple simultaneous categories per patient are supported.
    """

    __tablename__ = "patient_categories"
    __table_args__ = (UniqueConstraint("patient_id", "category_type"),)

    patient_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("patients.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    category_type: Mapped[PatientCategoryType] = mapped_column(
        _enum(PatientCategoryType, "patient_category_type"), nullable=False
    )
    effective_from: Mapped[date | None] = mapped_column(Date, nullable=True)
    effective_to: Mapped[date | None] = mapped_column(Date, nullable=True)
    assigned_by: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("staff_users.id", ondelete="SET NULL"),
        nullable=True,
    )

    patient: Mapped[Patient] = relationship(back_populates="categories")


class ConsentRecord(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """A patient consent or authorization record (PRD data model C).

    Communication consent is tracked separately from health-data authorization.
    """

    __tablename__ = "consent_records"

    patient_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("patients.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    consent_type: Mapped[ConsentType] = mapped_column(
        _enum(ConsentType, "consent_type"), nullable=False
    )
    purpose: Mapped[str] = mapped_column(String(255), nullable=False)
    status: Mapped[ConsentStatus] = mapped_column(
        _enum(ConsentStatus, "consent_status"), default=ConsentStatus.ACTIVE, nullable=False
    )
    captured_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    evidence_reference: Mapped[str | None] = mapped_column(String(255), nullable=True)
    recorded_by: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("staff_users.id", ondelete="SET NULL"),
        nullable=True,
    )

    patient: Mapped[Patient] = relationship(back_populates="consents")


class Observation(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """A dated, structured patient observation (PRD FR-018).

    Rows are append-only through the application: a new reading never overwrites
    a previous one. Each observation retains units, source and measurement
    context.
    """

    __tablename__ = "observations"
    __table_args__ = (Index("ix_observations_patient_time", "patient_id", "observed_at"),)

    patient_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("patients.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    follow_up_instance_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True), nullable=True
    )
    observation_type: Mapped[str] = mapped_column(String(50), index=True, nullable=False)
    value: Mapped[Decimal | None] = mapped_column(Numeric(14, 4), nullable=True)
    unit: Mapped[str | None] = mapped_column(String(20), nullable=True)
    observed_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    reported_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    source: Mapped[ObservationSource] = mapped_column(
        _enum(ObservationSource, "observation_source"), nullable=False
    )
    measurement_context: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)
    validation_status: Mapped[ObservationValidationStatus] = mapped_column(
        _enum(ObservationValidationStatus, "observation_validation_status"),
        default=ObservationValidationStatus.PENDING,
        nullable=False,
    )
    review_status: Mapped[ObservationReviewStatus] = mapped_column(
        _enum(ObservationReviewStatus, "observation_review_status"),
        default=ObservationReviewStatus.PENDING,
        nullable=False,
    )
    recorded_by: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("staff_users.id", ondelete="SET NULL"),
        nullable=True,
    )
    ai_extraction_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("ai_extractions.id", ondelete="SET NULL"),
        nullable=True,
    )

    patient: Mapped[Patient] = relationship(back_populates="observations")


class CarePlan(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """A patient-specific care plan, versioned (PRD FR-007).

    Historical assessments are evaluated against the plan version active at the
    relevant time, so versions are never overwritten.
    """

    __tablename__ = "care_plans"
    __table_args__ = (UniqueConstraint("patient_id", "version"),)

    patient_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("patients.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    version: Mapped[int] = mapped_column(Integer, nullable=False)
    status: Mapped[CarePlanStatus] = mapped_column(
        _enum(CarePlanStatus, "care_plan_status"), nullable=False
    )
    effective_from: Mapped[date | None] = mapped_column(Date, nullable=True)
    effective_to: Mapped[date | None] = mapped_column(Date, nullable=True)
    approved_by: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("staff_users.id", ondelete="SET NULL"),
        nullable=True,
    )
    approval_timestamp: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    plan_reference: Mapped[str | None] = mapped_column(String(255), nullable=True)
    content: Mapped[dict[str, Any] | None] = mapped_column(JSONB, nullable=True)

    patient: Mapped[Patient] = relationship(back_populates="care_plans")
